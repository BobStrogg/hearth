// Writes src/version.ts from package.json (so the version is compiled in, including into single-file binaries).
import { readFileSync, writeFileSync } from "node:fs";
const v = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")).version;
const out = `// Generated by scripts/gen-version.mjs from package.json. Do not edit.\nexport const VERSION = ${JSON.stringify(v)};\n`;
const p = new URL("../src/version.ts", import.meta.url);
let cur = ""; try { cur = readFileSync(p, "utf8"); } catch { /* first run */ }
if (cur !== out) writeFileSync(p, out);
